export function Icon({
  name,
  className,
  "aria-hidden": ariaHidden = true,
}: {
  name: string;
  className?: string;
  "aria-hidden"?: boolean;
}) {
  const Cmp = ICONS[name] ?? Info;
  return <Cmp className={className} aria-hidden={ariaHidden} />;
}
